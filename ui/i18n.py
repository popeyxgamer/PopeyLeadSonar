SUPPORTED_LANGUAGES = ["pl", "en", "de"]
LANGUAGE_NAMES = {"pl": "Polski", "en": "English", "de": "Deutsch"}
LANGUAGE_FLAGS = {"pl": "🇵🇱", "en": "🇬🇧", "de": "🇩🇪"}

_LANG_FILE = BASE_DIR / "app_language.txt"
_current_language = "pl"

def get_language() -> str:
    return _current_language

def set_language(code: str, persist: bool = True) -> None:
    global _current_language
    if code not in SUPPORTED_LANGUAGES:
        return
    _current_language = code
    if persist:
        try:
            _LANG_FILE.write_text(code, encoding="utf-8")
        except OSError:
            pass

def load_language_from_disk() -> str:
    global _current_language
    try:
        code = _LANG_FILE.read_text(encoding="utf-8").strip()
        if code in SUPPORTED_LANGUAGES:
            _current_language = code
    except (OSError, FileNotFoundError):
        pass
    return _current_language


def restart_app() -> None:
    """Restartuje cały proces aplikacji, żeby nowy język (albo inna zmiana
    wymagająca przebudowy całego GUI) był widoczny od razu, bez ręcznego
    zamykania i ponownego uruchamiania programu przez użytkownika.
    """
    import os
    import sys

    try:
        from PySide6.QtWidgets import QApplication
        app = QApplication.instance()
        if app is not None:
            app.closeAllWindows()
    except Exception:
        pass

    python = sys.executable
    os.execv(python, [python] + sys.argv)

def tr(text: str) -> str:
    if _current_language == "pl" or not text:
        return text
    table = TRANSLATIONS.get(_current_language)
    if not table:
        return text
    return table.get(text, text)

